/** 术语查找表：term 与 aliases 都映射到同一条释义。 */
export const TERM_LOOKUP: Map<string, LawTerm> = (() => {
  const m = new Map<string, LawTerm>();
  for (const t of LAW_TERMS) {
    m.set(t.term, t);
    for (const a of t.aliases ?? []) m.set(a, t);
  }
  return m;
})();

/** 按词条长度降序排列的匹配词表（长词优先，避免「仲裁」吃掉「仲裁前置」）。 */
export const TERM_MATCH_WORDS: string[] = (() => {
  const words = [...TERM_LOOKUP.keys()];
  return words.sort((a, b) => b.length - a.length);
})();

/** 从一段文本中提取出现的术语（去重；最长优先匹配，短词不重复计入已覆盖位置）。 */
export function extractTerms(text: string): LawTerm[] {
  const seen = new Set<string>();
  const hits: LawTerm[] = [];
  let i = 0;
  outer: while (i < text.length) {
    for (const w of TERM_MATCH_WORDS) {
      if (text.startsWith(w, i)) {
        const t = TERM_LOOKUP.get(w)!;
        if (!seen.has(t.term)) {
          seen.add(t.term);
          hits.push(t);
        }
        i += w.length;
        continue outer;
      }
    }
    i += 1;
  }
  return hits;
}
